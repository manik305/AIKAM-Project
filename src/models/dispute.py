from sqlalchemy import Column, String, Float, DateTime, ForeignKey, Text
from sqlalchemy.orm import relationship
from datetime import datetime
from src.core.database import Base


class DisputeTicket(Base):
    __tablename__ = "dispute_tickets"

    ticket_id = Column(String(36), primary_key=True, index=True)
    usc_number = Column(String(20), ForeignKey("consumer_connections.usc_number"), nullable=False)
    bill_id = Column(String(36), nullable=False)
    complaint_type = Column(String(50), nullable=False) # METER_READING_MISMATCH, DOOR_LOCK_AVERAGE
    reported_reading = Column(Float, nullable=False)
    billed_reading = Column(Float, nullable=False)
    disputed_amount = Column(Float, nullable=False)
    provisional_revised_amount = Column(Float, nullable=False)
    evidence_photo_url = Column(String(500), nullable=True)
    ocr_confidence_score = Column(Float, default=0.0)

    # Status & Workflow
    status = Column(String(20), default="SUBMITTED") # SUBMITTED, UNDER_REVIEW, APPROVED, REJECTED
    sap_ticket_reference = Column(String(50), nullable=True) # Reference generated by SAP BAPI
    resolution_notes = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)
    resolved_at = Column(DateTime, nullable=True)

    connection = relationship("ConsumerConnection", back_populates="disputes")
